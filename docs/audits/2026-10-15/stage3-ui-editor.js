  if (document.querySelector('#pixelEditorModal').classList.contains('hidden')) throw new Error('Редактор не открыт');
  if (pixelEditor.width !== 64 || pixelEditor.height !== 64) throw new Error('Редактор изменил холст');
  if (!state.source.paths[0].includes('chuba-sprite-sheet-')) throw new Error('Открыт исходник вместо результата');
  document.documentElement.dataset.shellMotion = 'off';
